function localizeOptions(options: TreeOption[] | undefined, labels: string[] | undefined) {
  if (!options || !labels) return options;
  return options.map((option, index) => ({ ...option, label: labels[index] ?? option.label }));
}

export function localizeNode(node: TreeNode, language: Language): TreeNode {
  if (language === 'en') return node;
  const copy = nepaliCopy[node.id];
  if (!copy) return node;
  return {
    ...node,
    text: copy.text,
    sub: copy.sub,
    options: localizeOptions(node.options, copy.options),
    items: node.items?.map((item, index) => ({ ...item, ...copy.items?.[index] })),
  };
}
